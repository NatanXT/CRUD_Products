-- Estrutura inicial do banco de dados para o CRUD de produtos.
-- A tabela "produtos" armazena os produtos cadastrados pela API.

CREATE TABLE IF NOT EXISTS public.produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    preco NUMERIC(10, 2) NOT NULL,
    quantidade INTEGER NOT NULL,

    CONSTRAINT chk_produtos_preco
        CHECK (preco >= 0),

    CONSTRAINT chk_produtos_quantidade
        CHECK (quantidade >= 0),

    CONSTRAINT chk_produtos_nome
        CHECK (LENGTH(BTRIM(nome)) > 0)
);
